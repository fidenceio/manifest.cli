#!/usr/bin/env bash
# env-k8s-render.sh — render k8s/env files from `manifest env export`.
#
# A REFERENCE, not a product. Manifest CLI used to write these files itself and
# no longer does: how variables reach a cluster is your platform's design, not
# a release tool's. Copy this script into your own repository, change it to fit
# your platform, and own it. Nothing in Manifest runs it or checks its output.
#
# It renders what Manifest rendered, from the same inputs:
#
#   configmap.yaml                 non-secret variables, for `envFrom`
#   kustomization.yaml             lists the files below, so an overlay can
#                                  reference the directory
#   external-secret.yaml           secret variables, as an External Secrets
#                                  Operator ExternalSecret   (--provider external-secrets)
#   component/kustomization.yaml   a kustomize Component that fills {env} in
#                                  every secret path per environment
#                                  (when --path contains {env})
#
# Usage:
#   manifest env export | env-k8s-render.sh [options]
#   env-k8s-render.sh [options] export.json
#
# Options:
#   --out DIR                 where to write (default: k8s/env)
#   --check                   write nothing; exit 1 if any file is out of date
#   --force                   replace a file this script did not generate
#   --identity NAME           name the objects NAME-env (default: the export's
#                             "identity", which is the repository's name)
#   --provider KIND           external-secrets | none (default: none). With
#                             `none`, secret variables are not rendered at all.
#   --store-name NAME         the SecretStore / ClusterSecretStore to read from
#   --store-kind KIND         default: ClusterSecretStore
#   --path TEMPLATE           where a secret lives in the store. Tokens:
#                             {env} {identity} {group} {name}
#   --property TEMPLATE       default: {name}. Tokens: {identity} {group} {name}
#   --env-label LABEL         the label {env} is read from, per environment
#   --api-version VERSION     default: external-secrets.io/v1
#   --refresh-interval DUR    default: 1h
#
# Needs: bash, and yq v4 (https://github.com/mikefarah/yq), which Manifest
# itself needs. Written to run on the bash 3.2 that macOS ships.
#
# Coming from Manifest's own rendering: pass the values your `env.secrets`
# settings held (provider, store.name, store.kind, path, property, env_label,
# api_version, refresh_interval) as the options above. Manifest named objects
# after the checkout's FOLDER; this names them after the repository. If the two
# differ and you need the old names, pass --identity <folder name>.

set -u

HEADER="# Generated by env-k8s-render.sh from \`manifest env export\`."
FORMER_HEADER="# Generated by Manifest CLI"

out_dir="k8s/env"
check_only=false
force=false
identity=""
provider="none"
store_name=""
store_kind="ClusterSecretStore"
path_template=""
property_template="{name}"
env_label=""
api_version="external-secrets.io/v1"
refresh_interval="1h"
input=""

die() {
    echo "env-k8s-render: $*" >&2
    exit 1
}

need_value() {
    [ "$#" -ge 2 ] || die "$1 needs a value"
}

while [ "$#" -gt 0 ]; do
    case "$1" in
        --out)              need_value "$@"; out_dir="$2"; shift ;;
        --check)            check_only=true ;;
        --force)            force=true ;;
        --identity)         need_value "$@"; identity="$2"; shift ;;
        --provider)         need_value "$@"; provider="$2"; shift ;;
        --store-name)       need_value "$@"; store_name="$2"; shift ;;
        --store-kind)       need_value "$@"; store_kind="$2"; shift ;;
        --path)             need_value "$@"; path_template="$2"; shift ;;
        --property)         need_value "$@"; property_template="$2"; shift ;;
        --env-label)        need_value "$@"; env_label="$2"; shift ;;
        --api-version)      need_value "$@"; api_version="$2"; shift ;;
        --refresh-interval) need_value "$@"; refresh_interval="$2"; shift ;;
        -h|--help)
            sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        -*) die "unknown option: $1 (see --help)" ;;
        *)
            [ -z "$input" ] || die "more than one input file given"
            input="$1"
            ;;
    esac
    shift
done

command -v yq >/dev/null 2>&1 || die "yq v4 is required"

# ---- Read the export ---------------------------------------------------------
tmp_dir="$(mktemp -d)" || die "could not create a temporary directory"
trap 'rm -rf "$tmp_dir"' EXIT
export_file="$tmp_dir/export.json"
if [ -n "$input" ]; then
    [ -f "$input" ] || die "no such file: $input"
    cat "$input" > "$export_file"
else
    [ -t 0 ] && die "no input: pipe \`manifest env export\` into this script, or name a file"
    cat > "$export_file"
fi
[ -s "$export_file" ] || die "the export is empty (did \`manifest env export\` fail?)"

q() {
    yq e -p=json "$1" "$export_file" 2>/dev/null
}

schema="$(q '.schema')" || die "the input is not JSON"
[ "$schema" = "1" ] || die "the input is not a schema 1 export (schema: ${schema:-none})"
[ -n "$identity" ] || identity="$(q '.identity // ""')"
[ -n "$identity" ] || die "the export carries no identity; pass --identity"
# The identity becomes object names and part of every secret path, unquoted.
printf '%s' "$identity" | grep -Eq '^[A-Za-z0-9._-]+$' \
    || die "identity '$identity' must be a plain name (letters, digits, '.', '_' and '-'); pass --identity"
[ "$(printf '%s' "$identity" | wc -l | tr -d ' ')" = "0" ] || die "identity spans more than one line"
printf '%s' "$store_kind" | grep -Eq '^[A-Za-z][A-Za-z0-9]*$' \
    || die "--store-kind '$store_kind' must be a kind name (letters and digits)"
[ "$(printf '%s' "$store_kind" | wc -l | tr -d ' ')" = "0" ] || die "--store-kind spans more than one line"
count="$(q '.env | length')"
case "$count" in ''|*[!0-9]*) die "the export has no env list" ;; esac

# ---- Check the entries and the settings --------------------------------------
# A name is written as a YAML key, unquoted. Accept what a ConfigMap key may
# be (letters, digits, '.', '_' and '-') and refuse anything else — a space, a
# colon, a quote, a line break — before anything is rendered.
plain_name() {
    [ "$(printf '%s' "$1" | wc -l | tr -d ' ')" = "0" ] \
        && printf '%s' "$1" | grep -Eq '^[A-Za-z0-9_.-]+$'
}

secret_count=0
i=0
while [ "$i" -lt "$count" ]; do
    entry_name="$(q ".env[$i].name")"
    plain_name "$entry_name" \
        || die "entry $((i + 1)): '$entry_name' is not a plain variable name (letters, digits, '.', '_' and '-')"
    entry_framework="$(q ".env[$i].framework_name // \"\"")"
    if [ -n "$entry_framework" ]; then
        plain_name "$entry_framework" \
            || die "$entry_name: framework_name '$entry_framework' is not a plain variable name"
    fi
    [ "$(q ".env[$i].secret")" = "true" ] && secret_count=$((secret_count + 1))
    i=$((i + 1))
done

# Index of the {env} segment in a '/'-delimited template: -1 when it has none,
# -2 when {env} is only part of a segment.
env_index_of() {
    case "$1" in *'{env}'*) ;; *) echo -1; return 0 ;; esac
    local rest="$1" seg n=0
    while :; do
        seg="${rest%%/*}"
        if [ "$seg" = '{env}' ]; then echo "$n"; return 0; fi
        [ "$rest" = "$seg" ] && break
        rest="${rest#*/}"
        n=$((n + 1))
    done
    echo -2
}

render_secrets=false
render_component=false
env_index=-1
problems=""
problem() { problems="${problems}  $1
"; }

case "$provider" in
    none) ;;
    external-secrets)
        if [ "$secret_count" -gt 0 ]; then
            render_secrets=true
            [ -n "$store_name" ] || problem "--store-name is not set"
            if [ -n "$store_name" ] && ! printf '%s' "$store_name" | grep -Eq '^[a-z0-9]([-a-z0-9.]*[a-z0-9])?$'; then
                problem "--store-name '$store_name' must be a Kubernetes object name (lowercase letters, digits, '-' and '.')"
            fi
            [ -n "$path_template" ] || problem "--path is not set (tokens: {env} {identity} {group} {name})"
            printf '%s' "$api_version" | grep -Eq '^[A-Za-z0-9][A-Za-z0-9./-]*$' \
                || problem "--api-version '$api_version' is not an API group/version"
            printf '%s' "$refresh_interval" | grep -Eq '^(0|([0-9]+(\.[0-9]+)?(ns|us|ms|s|m|h))+)$' \
                || problem "--refresh-interval '$refresh_interval' is not a duration (for example 1h, 30m, 90s, or 0)"
            # key and property are written double-quoted: a quote, a backslash
            # or whitespace in a template would escape the quoting.
            printf '%s' "$path_template" | grep -q '["\\[:space:]]' \
                && problem "--path may not contain quotes, backslashes or whitespace"
            printf '%s' "$property_template" | grep -q '["\\[:space:]]' \
                && problem "--property may not contain quotes, backslashes or whitespace"
            for token in $(printf '%s' "$path_template" | grep -oE '\{[^}]*\}' || true); do
                case "$token" in
                    '{env}'|'{identity}'|'{group}'|'{name}') ;;
                    *) problem "--path has an unknown token $token (known: {env} {identity} {group} {name})" ;;
                esac
            done
            for token in $(printf '%s' "$property_template" | grep -oE '\{[^}]*\}' || true); do
                case "$token" in
                    '{identity}'|'{group}'|'{name}') ;;
                    '{env}') problem "--property may not use {env}; only the path is filled per environment" ;;
                    *) problem "--property has an unknown token $token (known: {identity} {group} {name})" ;;
                esac
            done
            env_uses="$(printf '%s' "$path_template" | grep -o '{env}' | grep -c . || true)"
            [ "${env_uses:-0}" -gt 1 ] && problem "--path may use {env} once: the per-environment replacement fills one segment"
            env_index="$(env_index_of "$path_template")"
            if [ "$env_index" = "-2" ]; then
                problem "--path: {env} must be a whole path segment (between slashes)"
            elif [ "$env_index" != "-1" ]; then
                render_component=true
                if [ -z "$env_label" ]; then
                    problem "--env-label is not set, and the path has {env}"
                elif ! printf '%s' "$env_label" | grep -Eq '^[A-Za-z0-9_-]+$'; then
                    problem "--env-label '$env_label' must be a plain name (letters, digits, '-' and '_')"
                fi
            fi
        fi
        ;;
    *) problem "--provider '$provider' is not recognised (external-secrets | none)" ;;
esac
if [ -n "$problems" ]; then
    echo "env-k8s-render: cannot render:" >&2
    printf '%s' "$problems" >&2
    echo "Nothing was written." >&2
    exit 1
fi

expand() {
    # expand TEMPLATE GROUP NAME — {env} is left in place for the Component.
    local out="$1"
    out="${out//\{identity\}/$identity}"
    out="${out//\{group\}/$2}"
    out="${out//\{name\}/$3}"
    printf '%s' "$out"
}

# A value inside a double-quoted YAML scalar.
yaml_quoted() {
    local value="$1"
    value="${value//\\/\\\\}"
    value="${value//\"/\\\"}"
    printf '%s' "$value"
}

# ---- Render ------------------------------------------------------------------
render_configmap() {
    printf '%s\n' "$HEADER"
    printf '# Non-secret variables — inject with `envFrom`. Edit the spec, then re-run the script.\n'
    printf 'apiVersion: v1\n'
    printf 'kind: ConfigMap\n'
    printf 'metadata:\n'
    printf '  name: %s-env\n' "$identity"
    printf 'data:\n'
    local i=0 emitted=0 name default framework injected
    while [ "$i" -lt "$count" ]; do
        if [ "$(q ".env[$i].secret")" != "true" ]; then
            name="$(q ".env[$i].name")"
            default="$(q ".env[$i].default // \"\"")"
            framework="$(q ".env[$i].framework_name // \"\"")"
            injected="${framework:-$name}"
            case "$default" in
                *'
'*) die "$name: its default spans more than one line, which a ConfigMap value written on one line cannot hold" ;;
            esac
            printf '  %s: "%s"\n' "$injected" "$(yaml_quoted "$default")"
            emitted=$((emitted + 1))
        fi
        i=$((i + 1))
    done
    [ "$emitted" -gt 0 ] || printf '  {}\n'
}

render_external_secret() {
    printf '%s\n' "$HEADER"
    printf '# Secret variables — External Secrets Operator. {env} is filled per environment\n'
    printf '# by the component beside this file. Edit the spec, then re-run the script.\n'
    printf 'apiVersion: %s\n' "$api_version"
    printf 'kind: ExternalSecret\n'
    printf 'metadata:\n'
    printf '  name: %s-env\n' "$identity"
    printf 'spec:\n'
    printf '  refreshInterval: %s\n' "$refresh_interval"
    printf '  secretStoreRef:\n'
    printf '    name: %s\n' "$store_name"
    printf '    kind: %s\n' "$store_kind"
    printf '  target:\n'
    printf '    name: %s-env\n' "$identity"
    printf '    creationPolicy: Owner\n'
    printf '  data:\n'
    local i=0 name group framework injected key property
    while [ "$i" -lt "$count" ]; do
        if [ "$(q ".env[$i].secret")" = "true" ]; then
            name="$(q ".env[$i].name")"
            group="$(q ".env[$i].group // \"app\"")"
            framework="$(q ".env[$i].framework_name // \"\"")"
            injected="${framework:-$name}"
            key="$(expand "$path_template" "$group" "$name")"
            property="$(expand "$property_template" "$group" "$name")"
            # The templates were checked; what a {group} expands to was not.
            case "$key$property" in
                *[\"\\[:space:]]*) die "$name: its secret path or property would contain a quote, a backslash or whitespace (check its group: '$group')" ;;
            esac
            printf '    - secretKey: %s\n' "$injected"
            printf '      remoteRef:\n'
            # Quoted: a template that starts with {env} would otherwise parse
            # as a YAML flow mapping.
            printf '        key: "%s"\n' "$key"
            printf '        property: "%s"\n' "$property"
        fi
        i=$((i + 1))
    done
}

render_component() {
    printf '%s\n' "$HEADER"
    printf '# Fills {env} in every remoteRef.key of the ExternalSecret from the `%s`\n' "$env_label"
    printf '# label, per environment. kustomize runs a Component before the including\n'
    printf '# kustomization'"'"'s own transformers, so the label must already be on the\n'
    printf '# ExternalSecret when this is included: label it one layer down, in a\n'
    printf '# kustomization that references the DIRECTORY this file'"'"'s parent sits in.\n'
    printf '#   k8s/overlays/<environment>/env/kustomization.yaml\n'
    printf '#     resources: [ ../../../env ]\n'
    printf '#     labels: [ { pairs: { %s: <environment> } } ]\n' "$env_label"
    printf '#   k8s/overlays/<environment>/kustomization.yaml\n'
    printf '#     resources: [ env ]\n'
    printf '#     components: [ ../../env/component ]\n'
    printf 'apiVersion: kustomize.config.k8s.io/v1alpha1\n'
    printf 'kind: Component\n'
    printf 'replacements:\n'
    printf '  - source:\n'
    printf '      kind: ExternalSecret\n'
    printf '      name: %s-env\n' "$identity"
    printf '      fieldPath: metadata.labels.%s\n' "$env_label"
    printf '    targets:\n'
    printf '      - select:\n'
    printf '          kind: ExternalSecret\n'
    printf '          name: %s-env\n' "$identity"
    printf '        fieldPaths:\n'
    printf '          - spec.data.*.remoteRef.key\n'
    printf '        options:\n'
    printf '          delimiter: "/"\n'
    printf '          index: %s\n' "$env_index"
}

render_kustomization() {
    printf '%s\n' "$HEADER"
    printf '# Makes this directory a buildable base, so overlays can reference it.\n'
    printf 'apiVersion: kustomize.config.k8s.io/v1beta1\n'
    printf 'kind: Kustomization\n'
    printf 'resources:\n'
    printf '  - configmap.yaml\n'
    [ "$render_secrets" = "true" ] && printf '  - external-secret.yaml\n'
    return 0
}

# ---- Land --------------------------------------------------------------------
# A file is replaced only when this script, or Manifest before it, generated
# it. Anything else at the path is yours, and --force is how you say otherwise.
stale=0
blocked=0
land() {
    local rel="$1" rendered="$2" target="$out_dir/$1" first=""
    if [ -e "$target" ] && [ ! -f "$target" ]; then
        echo "  cannot write: $target (not a file)"
        blocked=$((blocked + 1))
        return 0
    fi
    if [ -s "$target" ]; then
        { IFS= read -r first < "$target"; } 2>/dev/null || true
        case "$first" in
            "$HEADER"*|"$FORMER_HEADER"*) ;;
            *)
                if [ "$force" != "true" ]; then
                    echo "  hand-authored, left untouched: $target (pass --force to replace it)"
                    return 0
                fi
                ;;
        esac
        if [ "$(cat "$target")" = "$rendered" ]; then
            echo "  up-to-date:   $target"
            return 0
        fi
    fi
    if [ "$check_only" = "true" ]; then
        echo "  out of date:  $target"
        stale=$((stale + 1))
        return 0
    fi
    mkdir -p "$(dirname "$target")" || { blocked=$((blocked + 1)); return 0; }
    if printf '%s\n' "$rendered" > "$target.tmp.$$" && mv "$target.tmp.$$" "$target"; then
        echo "  wrote:        $target"
    else
        rm -f "$target.tmp.$$"
        echo "  FAILED:       $target"
        blocked=$((blocked + 1))
    fi
}

# Render everything before anything is written, so a refusal leaves no half set.
configmap_rendered="$(render_configmap)" || exit 1
kustomization_rendered="$(render_kustomization)" || exit 1
secret_rendered=""
component_rendered=""
if [ "$render_secrets" = "true" ]; then
    secret_rendered="$(render_external_secret)" || exit 1
    if [ "$render_component" = "true" ]; then
        component_rendered="$(render_component)" || exit 1
    fi
fi

land "kustomization.yaml" "$kustomization_rendered"
land "configmap.yaml" "$configmap_rendered"
if [ "$render_secrets" = "true" ]; then
    land "external-secret.yaml" "$secret_rendered"
    [ "$render_component" = "true" ] && land "component/kustomization.yaml" "$component_rendered"
elif [ "$secret_count" -gt 0 ]; then
    echo "  note: $secret_count secret variable(s) are not rendered (--provider none)"
fi

if [ "$blocked" -gt 0 ]; then
    echo "env-k8s-render: $blocked file(s) could not be written" >&2
    exit 1
fi
if [ "$check_only" = "true" ] && [ "$stale" -gt 0 ]; then
    echo "env-k8s-render: $stale file(s) out of date — re-run without --check" >&2
    exit 1
fi
exit 0
