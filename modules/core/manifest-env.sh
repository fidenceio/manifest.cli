#!/bin/bash

# Manifest CLI Env Module — `manifest env` (ENV-001, STANDARD.md §2.7)
#
# The spec `env:` block (service.spec.yaml / app.spec.yaml) is the single
# source of truth (D-ENV-2). This module generates the bridge outputs from it:
#
#   .env.example                    stored-name schema template (always)
#   k8s/env/configmap.yaml          non-secret bridge (when k8s/ exists)
#   k8s/env/external-secret.yaml    secret bridge via External Secrets Operator
#                                   (when k8s/ exists, secrets are declared, and
#                                   env.secrets.provider is external-secrets)
#   k8s/env/component/kustomization.yaml
#                                   kustomize Component that fills {env} in
#                                   every remoteRef.key per environment (when
#                                   the path template has {env})
#   Dockerfile marker block         build-time publics ARG→ENV bridge
#
# The secret store is configuration, never a built-in (env.secrets.*, resolved
# by _manifest_env_secrets_setting in manifest-init.sh). A spec that declares
# secret variables with no env.secrets configured FAILS CLOSED: generate exits
# non-zero and writes nothing.
#
# Two refusals sit in front of every write (TRACKER §98, §3(d)):
#   - a secret / required / public flag that is neither true nor false is
#     refused by name, never read as false (_manifest_env_spec_flag);
#   - an existing file whose first line is not the header Manifest writes there
#     is hand-authored: left untouched, never drift (_manifest_env_guarded_state).
#
# `env generate` previews by default, applies with -y, and gates drift with
# --check (the run-tests.sh stanza). `env validate` = env prefix policy + drift +
# gitignore hygiene, read-only.

# Guard against multiple sourcing
if [[ -n "${_MANIFEST_CLI_ENV_LOADED:-}" ]]; then
    return 0
fi
_MANIFEST_CLI_ENV_LOADED=1

MANIFEST_CLI_ENV_BRIDGE_BEGIN="# --- manifest env bridge (generated — edit the spec, not this block) ---"
MANIFEST_CLI_ENV_BRIDGE_END="# --- end manifest env bridge ---"

# What the first line of a file Manifest generated starts with. Every release
# that has written these files wrote one of these (`git log -S` over this
# module and manifest-init.sh), so a file whose first line starts otherwise
# was not written by Manifest. .env.example has two: `env generate` writes the
# first, the init scaffold's starter the second.
MANIFEST_CLI_ENV_K8S_HEADER="# Generated by Manifest CLI"
MANIFEST_CLI_ENV_EXAMPLE_HEADER_GENERATED="# .env.example — generated by Manifest CLI"
MANIFEST_CLI_ENV_EXAMPLE_HEADER_SCAFFOLDED="# .env.example — scaffolded by Manifest CLI"

# Does the repo's spec have a non-empty env: block?
_manifest_env_spec_ready() {
    local project_root="$1"
    local spec_file
    spec_file="$(_manifest_env_spec_file "$project_root")"
    [[ -n "$spec_file" ]] || return 1
    command -v yq >/dev/null 2>&1 || return 1
    [[ "$(yq e '.env | length > 0' "$spec_file" 2>/dev/null)" == "true" ]]
}

# Render the generated ConfigMap (non-secret bridge): injected name =
# framework_name (or the FIDENCE name when no bridge is needed), value =
# spec default. Per-{env} values are overlay patches on top of this base.
_manifest_env_render_configmap() {
    local spec_file="$1"
    local project_root="$2"
    local repo_dir
    repo_dir="$(basename "$project_root")"

    printf '# Generated by Manifest CLI from %s `env:` (ENV-001, STANDARD.md §2.7).\n' "$(basename "$spec_file")"
    printf '# Non-secret bridge — inject via `envFrom`. Regenerate: manifest env generate -y\n'
    printf 'apiVersion: v1\n'
    printf 'kind: ConfigMap\n'
    printf 'metadata:\n'
    printf '  name: %s-env\n' "$repo_dir"
    printf 'data:\n'

    local count i name default secret_flag framework_name injected emitted=0
    count="$(yq e '.env | length' "$spec_file" 2>/dev/null)"
    [[ "$count" =~ ^[0-9]+$ ]] || count=0
    for ((i = 0; i < count; i++)); do
        name="$(yq e ".env[$i].name // \"\"" "$spec_file" 2>/dev/null)"
        [[ -n "$name" ]] || continue
        # A flag the reader refuses stops the render (§98): the ConfigMap is
        # the one file where "not a secret" publishes the default.
        secret_flag="$(_manifest_env_spec_flag "$spec_file" "$i" secret)" || return 1
        [[ "$secret_flag" == "true" ]] && continue
        default="$(yq e ".env[$i].default // \"\"" "$spec_file" 2>/dev/null)"
        framework_name="$(yq e ".env[$i].framework_name // \"\"" "$spec_file" 2>/dev/null)"
        injected="${framework_name:-$name}"
        printf '  %s: "%s"\n' "$injected" "$default"
        emitted=$((emitted + 1))
    done
    if [[ "$emitted" -eq 0 ]]; then
        printf '  {}\n'
    fi
}

# Names of the spec's secret variables, one per line (empty when none).
# Reads the flag through _manifest_env_spec_flag, as every renderer does, so
# the gate and the renderers cannot disagree about what a secret is: a gate
# that only accepted the YAML boolean once let a quoted `secret: "true"`
# through unconfigured. Returns 1 on a flag the reader refuses; generate has
# already refused that spec by name before this is called.
_manifest_env_spec_secret_names() {
    local spec_file="$1"
    local count i name secret_flag
    count="$(yq e '.env | length' "$spec_file" 2>/dev/null)"
    [[ "$count" =~ ^[0-9]+$ ]] || count=0
    for ((i = 0; i < count; i++)); do
        name="$(yq e ".env[$i].name // \"\"" "$spec_file" 2>/dev/null)"
        [[ -n "$name" ]] || continue
        secret_flag="$(_manifest_env_spec_flag "$spec_file" "$i" secret)" || return 1
        [[ "$secret_flag" == "true" ]] && printf '%s\n' "$name"
    done
    return 0
}

# Every problem with env.secrets for this spec, one per line on stdout; exit
# 1 when there is at least one. No secret variables → nothing to configure.
# This is the fail-closed gate: `env generate` refuses on any line here.
_manifest_env_secrets_problems() {
    local spec_file="$1"
    local -a secret_names=()
    local line
    while IFS= read -r line; do
        secret_names+=("$line")
    done < <(_manifest_env_spec_secret_names "$spec_file")
    [[ ${#secret_names[@]} -gt 0 ]] || return 0

    local provider problems=0
    provider="$(_manifest_env_secrets_setting provider)"
    case "$provider" in
        "")
            local joined
            joined="$(printf '%s, ' "${secret_names[@]}")"
            echo "env.secrets.provider is not set, but ${#secret_names[@]} secret variable(s) are declared: ${joined%, }"
            echo "Set env.secrets in manifest.config.yaml at the fleet root (or in this repo, which wins): provider external-secrets with store.name and path, or provider none when secrets reach the workload some other way. There is no built-in store."
            return 1
            ;;
        none)
            return 0
            ;;
        external-secrets)
            ;;
        *)
            echo "env.secrets.provider '${provider}' is not recognised (external-secrets | none)"
            return 1
            ;;
    esac

    local store_name path property env_label
    store_name="$(_manifest_env_secrets_setting store_name)"
    path="$(_manifest_env_secrets_setting path)"
    property="$(_manifest_env_secrets_setting property)"
    env_label="$(_manifest_env_secrets_setting env_label)"

    if [[ -z "$store_name" ]]; then
        echo "env.secrets.store.name is not set"
        problems=$((problems + 1))
    elif [[ ! "$store_name" =~ ^[a-z0-9]([-a-z0-9.]*[a-z0-9])?$ || "$store_name" == *..* ]]; then
        # A Kubernetes object name (DNS-1123), which is also what keeps the
        # unquoted YAML scalar a scalar.
        echo "env.secrets.store.name '${store_name}' must be a Kubernetes object name (lowercase letters, digits, '-' and '.')"
        problems=$((problems + 1))
    fi
    if [[ -z "$path" ]]; then
        echo "env.secrets.path is not set (tokens: {env} {identity} {group} {name})"
        problems=$((problems + 1))
    fi

    local api_version refresh_interval
    api_version="$(_manifest_env_secrets_setting api_version)"
    refresh_interval="$(_manifest_env_secrets_setting refresh_interval)"
    if [[ ! "$api_version" =~ ^[A-Za-z0-9][A-Za-z0-9./-]*$ ]]; then
        echo "env.secrets.api_version '${api_version}' is not an API group/version (letters, digits, '.', '/' and '-')"
        problems=$((problems + 1))
    fi
    # A Go duration; bare `0` is the "fetch once" spelling the operator documents.
    if [[ ! "$refresh_interval" =~ ^(0|([0-9]+(\.[0-9]+)?(ns|us|ms|s|m|h))+)$ ]]; then
        echo "env.secrets.refresh_interval '${refresh_interval}' is not a duration (for example 1h, 30m, 90s, or 0 to fetch once)"
        problems=$((problems + 1))
    fi
    # key and property are emitted double-quoted; a quote, a backslash or
    # whitespace in the template would escape the quoting or retype the value.
    if [[ "$path" =~ [\"\\[:space:]] ]]; then
        echo "env.secrets.path may not contain quotes, backslashes or whitespace"
        problems=$((problems + 1))
    fi
    if [[ "$property" =~ [\"\\[:space:]] ]]; then
        echo "env.secrets.property may not contain quotes, backslashes or whitespace"
        problems=$((problems + 1))
    fi
    local env_count
    env_count="$(printf '%s' "$path" | grep -o '{env}' | grep -c . || true)"
    if [[ "$env_count" -gt 1 ]]; then
        echo "env.secrets.path may use {env} once: the per-environment replacement fills one segment, and a second {env} would ship literally"
        problems=$((problems + 1))
    fi

    local token
    while IFS= read -r token; do
        [[ -n "$token" ]] || continue
        case "$token" in
            '{env}'|'{identity}'|'{group}'|'{name}') ;;
            *)
                echo "env.secrets.path has an unknown token ${token} (known: {env} {identity} {group} {name})"
                problems=$((problems + 1))
                ;;
        esac
    done < <(printf '%s' "$path" | grep -oE '\{[^}]*\}' || true)
    while IFS= read -r token; do
        [[ -n "$token" ]] || continue
        case "$token" in
            '{env}')
                echo "env.secrets.property may not use {env}; only the path is filled per environment"
                problems=$((problems + 1))
                ;;
            '{identity}'|'{group}'|'{name}') ;;
            *)
                echo "env.secrets.property has an unknown token ${token} (known: {identity} {group} {name})"
                problems=$((problems + 1))
                ;;
        esac
    done < <(printf '%s' "$property" | grep -oE '\{[^}]*\}' || true)

    local env_index
    env_index="$(_manifest_env_secrets_env_index "$path")"
    if [[ "$env_index" == "-2" ]]; then
        echo "env.secrets.path: {env} must be a whole path segment (between slashes), because the per-environment replacement addresses it by segment index"
        problems=$((problems + 1))
    elif [[ "$env_index" != "-1" ]]; then
        if [[ -z "$env_label" ]]; then
            echo "env.secrets.env_label is not set, and the path has {env}: the per-environment Component reads the environment from that label"
            problems=$((problems + 1))
        elif [[ ! "$env_label" =~ ^[A-Za-z0-9_-]+$ ]]; then
            echo "env.secrets.env_label '${env_label}' must be a plain name (letters, digits, '-' and '_'): kustomize addresses a label by a dotted field path, so a key containing '.' or '/' cannot be referenced"
            problems=$((problems + 1))
        fi
    fi

    [[ "$problems" -eq 0 ]]
}

# Render the generated ExternalSecret (secret bridge, D-ENV-3): secretKey =
# injected framework name, remoteRef.property = the stored name by default,
# remoteRef.key = the env.secrets.path template with {identity} {group}
# {name} expanded. `{env}` stays literal here; the Component fills it per
# environment. Called only when secrets are declared and the provider is
# external-secrets.
_manifest_env_render_external_secret() {
    local spec_file="$1"
    local project_root="$2"
    local repo_dir
    repo_dir="$(basename "$project_root")"
    local path_template property_template
    path_template="$(_manifest_env_secrets_setting path)"
    property_template="$(_manifest_env_secrets_setting property)"

    printf '# Generated by Manifest CLI from %s `env:` (ENV-001, STANDARD.md §2.7).\n' "$(basename "$spec_file")"
    printf '# Secret bridge — External Secrets Operator. Store and path come from\n'
    printf '# env.secrets in manifest.config.yaml; {env} is filled per environment by\n'
    printf '# k8s/env/component. Regenerate: manifest env generate -y\n'
    printf 'apiVersion: %s\n' "$(_manifest_env_secrets_setting api_version)"
    printf 'kind: ExternalSecret\n'
    printf 'metadata:\n'
    printf '  name: %s-env\n' "$repo_dir"
    printf 'spec:\n'
    printf '  refreshInterval: %s\n' "$(_manifest_env_secrets_setting refresh_interval)"
    printf '  secretStoreRef:\n'
    printf '    name: %s\n' "$(_manifest_env_secrets_setting store_name)"
    printf '    kind: %s\n' "$(_manifest_env_secrets_setting store_kind)"
    printf '  target:\n'
    printf '    name: %s-env\n' "$repo_dir"
    printf '    creationPolicy: Owner\n'
    printf '  data:\n'

    local count i name secret_flag framework_name group injected emitted=0
    count="$(yq e '.env | length' "$spec_file" 2>/dev/null)"
    [[ "$count" =~ ^[0-9]+$ ]] || count=0
    for ((i = 0; i < count; i++)); do
        name="$(yq e ".env[$i].name // \"\"" "$spec_file" 2>/dev/null)"
        [[ -n "$name" ]] || continue
        secret_flag="$(_manifest_env_spec_flag "$spec_file" "$i" secret)" || return 1
        [[ "$secret_flag" == "true" ]] || continue
        framework_name="$(yq e ".env[$i].framework_name // \"\"" "$spec_file" 2>/dev/null)"
        group="$(yq e ".env[$i].group // \"app\"" "$spec_file" 2>/dev/null)"
        injected="${framework_name:-$name}"
        printf '    - secretKey: %s\n' "$injected"
        printf '      remoteRef:\n'
        # Quoted: a template that starts with {env} would otherwise parse as a
        # YAML flow mapping.
        printf '        key: "%s"\n' "$(_manifest_env_secrets_expand "$path_template" "$repo_dir" "$group" "$name")"
        printf '        property: "%s"\n' "$(_manifest_env_secrets_expand "$property_template" "$repo_dir" "$group" "$name")"
        emitted=$((emitted + 1))
    done
    if [[ "$emitted" -eq 0 ]]; then
        printf '    []\n'
    fi
}

# Render the kustomize Component that fills {env} per environment: one
# replacement reads the env_label label off the ExternalSecret and writes it
# into the {env} segment of every remoteRef.key. The segment index comes from
# where {env} sits in the path template. Called only when the template has a
# whole-segment {env}.
_manifest_env_render_env_component() {
    local spec_file="$1"
    local project_root="$2"
    local repo_dir env_label env_index
    repo_dir="$(basename "$project_root")"
    env_label="$(_manifest_env_secrets_setting env_label)"
    env_index="$(_manifest_env_secrets_env_index "$(_manifest_env_secrets_setting path)")"

    printf '# Generated by Manifest CLI from %s `env:`.\n' "$(basename "$spec_file")"
    printf '# Fills {env} in every remoteRef.key of the ExternalSecret from the `%s`\n' "$env_label"
    printf '# label, per environment. kustomize runs a Component before the including\n'
    printf '# kustomization'"'"'s own transformers, so the label must already be on the\n'
    printf '# ExternalSecret when this is included: label it one layer down, in a\n'
    printf '# kustomization that references the k8s/env DIRECTORY (its kustomization.yaml\n'
    printf '# is generated beside this file; a file outside the referencing directory is\n'
    printf '# refused by kustomize).\n'
    printf '#   k8s/overlays/<environment>/env/kustomization.yaml\n'
    printf '#     resources: [ ../../../env ]\n'
    printf '#     labels: [ { pairs: { %s: <environment> } } ]\n' "$env_label"
    printf '#   k8s/overlays/<environment>/kustomization.yaml\n'
    printf '#     resources: [ env ]\n'
    printf '#     components: [ ../../env/component ]\n'
    printf '# Regenerate: manifest env generate -y\n'
    printf 'apiVersion: kustomize.config.k8s.io/v1alpha1\n'
    printf 'kind: Component\n'
    printf 'replacements:\n'
    printf '  - source:\n'
    printf '      kind: ExternalSecret\n'
    printf '      name: %s-env\n' "$repo_dir"
    printf '      fieldPath: metadata.labels.%s\n' "$env_label"
    printf '    targets:\n'
    printf '      - select:\n'
    printf '          kind: ExternalSecret\n'
    printf '          name: %s-env\n' "$repo_dir"
    printf '        fieldPaths:\n'
    printf '          - spec.data.*.remoteRef.key\n'
    printf '        options:\n'
    printf '          delimiter: "/"\n'
    printf '          index: %s\n' "$env_index"
}

# Render k8s/env/kustomization.yaml, which makes the bridge directory a
# buildable base. An overlay may only reference a FILE in or below its own
# directory, so the per-environment layer that labels the ExternalSecret has
# to reference this directory, not the file.
_manifest_env_render_env_kustomization() {
    local spec_file="$1"
    local with_secret_bridge="$2"

    printf '# Generated by Manifest CLI from %s `env:`.\n' "$(basename "$spec_file")"
    printf '# Makes k8s/env a buildable base: kustomize refuses a file outside the\n'
    printf '# referencing kustomization'"'"'s directory, so overlays reference this directory.\n'
    printf '# Regenerate: manifest env generate -y\n'
    printf 'apiVersion: kustomize.config.k8s.io/v1beta1\n'
    printf 'kind: Kustomization\n'
    printf 'resources:\n'
    printf '  - configmap.yaml\n'
    if [[ "$with_secret_bridge" == "true" ]]; then
        printf '  - external-secret.yaml\n'
    fi
}

# Disposition of a file `env generate` writes whole: the ordinary
# create|update|current, plus two that stop a write (TRACKER §3(d)).
#
#   foreign   an existing, non-empty file whose first line starts with none of
#             the given headers. It is hand-authored: never replaced, never
#             counted as drift. Before this guard reached every writer, a k8s/
#             directory was the whole test, and -y replaced a ConfigMap, an
#             ExternalSecret or a Component whatever it held.
#   blocked   something is at the path that cannot be read as a file — a
#             directory, or a file this user cannot read. Whether it is
#             hand-authored cannot be told, so it is neither compared nor
#             written: --check and -y exit 1 and name it.
#
# An empty file holds nothing to protect and is replaced. A symlink to a file
# is followed, as the redirects this replaced followed it; a symlink to
# nothing is `blocked`, because landing through it would create its target —
# and that target's missing directories — wherever it points.
#   _manifest_env_guarded_state <target> <rendered> <header> [<header> ...]
_manifest_env_guarded_state() {
    local target="$1" rendered="$2"
    shift 2
    if [[ -L "$target" && ! -e "$target" ]]; then
        printf 'blocked'
        return 0
    fi
    if [[ -e "$target" ]]; then
        if [[ ! -f "$target" || ! -r "$target" ]]; then
            printf 'blocked'
            return 0
        fi
        if [[ -s "$target" ]]; then
            local first="" header ours=false
            { IFS= read -r first < "$target"; } 2>/dev/null || true
            for header in "$@"; do
                [[ "$first" == "$header"* ]] && ours=true
            done
            if [[ "$ours" != "true" ]]; then
                printf 'foreign'
                return 0
            fi
        fi
    fi
    _manifest_env_artifact_state "$target" "$rendered"
}

# Land one generated file under -y. A hand-authored file is left alone; any
# other goes through the staged rename, which keeps the file's mode and leaves
# the old contents in place if the write fails.
#   _manifest_env_land <project-root> <relative-path> <state> <rendered>
_manifest_env_land() {
    local project_root="$1" rel="$2" state="$3" rendered="$4"
    if [[ "$state" == "foreign" ]]; then
        echo "  left:  $rel (hand-authored)"
        return 0
    fi
    if [[ "$state" == "blocked" ]]; then
        echo "  FAILED: $rel (not written)"
        return 1
    fi
    if printf '%s\n' "$rendered" | manifest_replace_file_atomically "$project_root/$rel" -; then
        echo "  wrote: $rel"
        return 0
    fi
    echo "  FAILED: $rel (not written)"
    return 1
}

# Drift detail for an existing external-secret.yaml that no longer matches:
# names the store or path the file carries against what config says, one line
# each, so the plan says WHAT drifted rather than only that something did.
_manifest_env_secrets_drift_detail() {
    local target="$1"
    local rendered="$2"
    [[ -f "$target" ]] || return 0

    local file_store file_kind file_key want_store want_kind want_key
    file_store="$(yq e '.spec.secretStoreRef.name // ""' "$target" 2>/dev/null)"
    file_kind="$(yq e '.spec.secretStoreRef.kind // ""' "$target" 2>/dev/null)"
    file_key="$(yq e '.spec.data[0].remoteRef.key // ""' "$target" 2>/dev/null)"
    want_store="$(printf '%s\n' "$rendered" | yq e '.spec.secretStoreRef.name // ""' - 2>/dev/null)"
    want_kind="$(printf '%s\n' "$rendered" | yq e '.spec.secretStoreRef.kind // ""' - 2>/dev/null)"
    want_key="$(printf '%s\n' "$rendered" | yq e '.spec.data[0].remoteRef.key // ""' - 2>/dev/null)"

    if [[ "$file_store" != "$want_store" || "$file_kind" != "$want_kind" ]]; then
        echo "store drift: file names ${file_kind:-?}/${file_store:-?}, config says ${want_kind}/${want_store}"
    fi
    if [[ "$file_key" != "$want_key" ]]; then
        echo "path drift: file's first key is ${file_key:-<none>}, config renders $(_manifest_env_secrets_setting path) as ${want_key:-<none>}"
    fi
}

# Render the Dockerfile ARG→ENV bridge block for build-time publics
# (public: true). Empty output = no public vars, no block.
_manifest_env_render_dockerfile_bridge() {
    local spec_file="$1"

    local count i name public framework_name injected lines=""
    count="$(yq e '.env | length' "$spec_file" 2>/dev/null)"
    [[ "$count" =~ ^[0-9]+$ ]] || count=0
    for ((i = 0; i < count; i++)); do
        name="$(yq e ".env[$i].name // \"\"" "$spec_file" 2>/dev/null)"
        [[ -n "$name" ]] || continue
        public="$(_manifest_env_spec_flag "$spec_file" "$i" public)" || return 1
        [[ "$public" == "true" ]] || continue
        framework_name="$(yq e ".env[$i].framework_name // \"\"" "$spec_file" 2>/dev/null)"
        injected="${framework_name:-$name}"
        lines+="ARG ${name}"$'\n'
        lines+="ENV ${injected}=\${${name}}"$'\n'
    done
    [[ -n "$lines" ]] || return 0

    printf '%s\n' "$MANIFEST_CLI_ENV_BRIDGE_BEGIN"
    printf '%s' "$lines"
    printf '%s\n' "$MANIFEST_CLI_ENV_BRIDGE_END"
}

# Extract the current bridge block from a Dockerfile (empty if none).
_manifest_env_dockerfile_bridge_current() {
    local dockerfile="$1"
    [[ -f "$dockerfile" ]] || return 0
    awk -v begin="$MANIFEST_CLI_ENV_BRIDGE_BEGIN" -v end="$MANIFEST_CLI_ENV_BRIDGE_END" '
        $0 == begin { inside = 1 }
        inside { print }
        $0 == end { inside = 0 }
    ' "$dockerfile"
}

# Replace (or append) the bridge block in a Dockerfile.
_manifest_env_dockerfile_bridge_apply() {
    local dockerfile="$1"
    local block="$2"
    local tmp rc=0
    tmp="$(mktemp)" || return 1

    if grep -qF "$MANIFEST_CLI_ENV_BRIDGE_BEGIN" "$dockerfile" 2>/dev/null; then
        # The block reaches awk through the environment, not `-v block=…`: it
        # is several lines, and BWK awk (macOS) refuses a newline inside a -v
        # value ("newline in string", exit 2) — so on macOS an existing block
        # could never be updated: a warning, exit 0, and --check red for good.
        MANIFEST_CLI_ENV_BRIDGE_BLOCK="$block" awk -v begin="$MANIFEST_CLI_ENV_BRIDGE_BEGIN" -v end="$MANIFEST_CLI_ENV_BRIDGE_END" '
            $0 == begin { inside = 1; print ENVIRON["MANIFEST_CLI_ENV_BRIDGE_BLOCK"]; next }
            $0 == end { inside = 0; next }
            !inside { print }
        ' "$dockerfile" > "$tmp" || { rm -f "$tmp"; return 1; }
    else
        cat "$dockerfile" > "$tmp" || { rm -f "$tmp"; return 1; }
        printf '\n%s\n' "$block" >> "$tmp"
    fi
    # Not `mv "$tmp" "$dockerfile"`: mktemp creates 0600 and a rename carries
    # those bits onto the target — measured, a 644 Dockerfile came back 600.
    manifest_replace_file_atomically "$dockerfile" "$tmp" || rc=1
    rm -f "$tmp"
    return "$rc"
}

# One artifact's disposition for generate/preview/check.
#   states: create | update | current
_manifest_env_artifact_state() {
    local target="$1"
    local rendered="$2"
    if [[ ! -f "$target" ]]; then
        printf 'create'
    elif [[ "$(cat "$target")" == "$rendered" ]]; then
        printf 'current'
    else
        printf 'update'
    fi
}

# manifest env generate [--check] [--dry-run] [-y|--yes]
manifest_env_generate() {
    local execution_mode="preview"
    local check_only=false
    local _local_only=false
    local remaining_args=()
    if ! manifest_execution_parse execution_mode _local_only remaining_args "$@"; then
        return 1
    fi
    set -- "${remaining_args[@]}"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --check) check_only=true ;;
            --help)
                _render_help \
                    "manifest env generate [--check] [--dry-run] [-y|--yes]" \
                    "Write the env files your spec's env: block describes, so the variable
names live in one place instead of being retyped per deployment target." \
                    "Options" "  --dry-run    Explicit preview; no writes (default)
  --check      Exit 1 if any generated file is out of date (for CI)
  -y, --yes    Write the files" \
                    "Files written" "  .env.example                  every variable name; non-secrets carry their
                                spec default (blank when the spec sets none),
                                secrets are commented out and left valueless
  k8s/env/kustomization.yaml    lists the bridges, so overlays can reference
                                the k8s/env directory (if k8s/ exists)
  k8s/env/configmap.yaml        Kubernetes non-secret values (if k8s/ exists)
  k8s/env/external-secret.yaml  Kubernetes secret refs, via External Secrets
                                Operator (if k8s/ exists and secrets are
                                declared); store and path come from env.secrets
  k8s/env/component/kustomization.yaml
                                kustomize Component that fills {env} in each
                                secret path per environment (if the path has it)
  Dockerfile bridge block       build-time public vars, ARG→ENV (if present)
  A file you wrote by hand at one of these paths (its first line is not the
  Manifest header) is left untouched and is not counted as out of date." \
                    "Spec flags" "  secret, required and public take true or false. Any other value (yes,
  on, 1) is refused by name: generate exits 1 and writes nothing." \
                    "Secret store" "  There is no built-in store. With secret variables declared and no
  env.secrets configured, generate exits 1 and writes nothing. Set, at the
  fleet root or per repo (the repo wins):
    env.secrets.provider          external-secrets | none
    env.secrets.store.name        the SecretStore / ClusterSecretStore name
    env.secrets.store.kind        default ClusterSecretStore
    env.secrets.path              template; tokens {env} {identity} {group} {name}
    env.secrets.property          template; default {name}
    env.secrets.env_label         label the {env} value is read from
    env.secrets.api_version       default external-secrets.io/v1
    env.secrets.refresh_interval  default 1h"
                return 0
                ;;
            *)
                _render_help_error "Unknown option: $1" "manifest env generate [--check] [--dry-run] [-y|--yes]"
                return 1
                ;;
        esac
        shift
    done

    local project_root="${MANIFEST_CLI_PROJECT_ROOT:-$(pwd)}"
    local spec_file
    spec_file="$(_manifest_env_spec_file "$project_root")"

    if ! _manifest_env_spec_ready "$project_root"; then
        # No STANDARD.md reference here. It is a Fidence-workspace document and
        # does not ship with the CLI, so for anyone who installed via Homebrew
        # this message used to cite a file they cannot open.
        echo "No spec env: block found (service.spec.yaml / app.spec.yaml)."
        echo "List your environment variables under 'env:' in that file first — it is"
        echo "the one place they are declared, and everything else is generated from"
        echo "it. To create a starter spec: manifest init repo -y"
        # Nothing to generate is not drift.
        return 0
    fi

    local apply=false
    [[ "$execution_mode" == "apply" && "$check_only" != "true" ]] && apply=true

    # ---- Refuse a flag that is neither true nor false ------------------------
    # Before the secret-store gate, which counts only the entries it reads as
    # secret: a `secret: yes` entry read as "not a secret" passed that gate
    # with no env.secrets at all (§98). Preview, --check and -y all exit 1.
    local flag_problems
    if ! flag_problems="$(_manifest_env_spec_flag_problems "$spec_file")"; then
        echo ""
        echo "env spec — cannot generate: $project_root"
        echo ""
        printf '%s\n' "$flag_problems" | sed 's/^/  /'
        echo ""
        echo "A flag is a YAML boolean; spellings such as yes, on or 1 are not guessed."
        echo "Nothing was written. Fix $(basename "$spec_file"), then: manifest env generate -y"
        return 1
    fi

    # ---- Fail closed on the secret store ------------------------------------
    # Secret variables with no (or a broken) env.secrets: refuse before anything
    # is rendered, so preview, --check and -y all exit 1 and nothing is written.
    local problems
    if ! problems="$(_manifest_env_secrets_problems "$spec_file")"; then
        echo ""
        echo "env.secrets — cannot generate: $project_root"
        echo ""
        printf '%s\n' "$problems" | sed 's/^/  /'
        echo ""
        echo "Nothing was written. Fix env.secrets, then: manifest env generate -y"
        return 1
    fi

    # ---- Render everything first (read-only) --------------------------------
    local example_rendered configmap_rendered external_rendered component_rendered bridge_rendered
    example_rendered="$(_manifest_env_render_example "$spec_file" "$project_root")"
    configmap_rendered="$(_manifest_env_render_configmap "$spec_file" "$project_root")"
    bridge_rendered="$(_manifest_env_render_dockerfile_bridge "$spec_file")"

    # The secret bridge exists only when there is something to bridge AND a
    # provider to bridge it through; the Component only when {env} needs filling.
    local emit_secret_bridge=false emit_component=false
    if [[ -n "$(_manifest_env_spec_secret_names "$spec_file")" \
          && "$(_manifest_env_secrets_setting provider)" == "external-secrets" ]]; then
        emit_secret_bridge=true
        external_rendered="$(_manifest_env_render_external_secret "$spec_file" "$project_root")"
        if [[ "$(_manifest_env_secrets_env_index "$(_manifest_env_secrets_setting path)")" -ge 0 ]]; then
            emit_component=true
            component_rendered="$(_manifest_env_render_env_component "$spec_file" "$project_root")"
        fi
    fi

    local -a plan_names=() plan_states=()
    local example_state
    example_state="$(_manifest_env_guarded_state "$project_root/.env.example" "$example_rendered" \
        "$MANIFEST_CLI_ENV_EXAMPLE_HEADER_GENERATED" "$MANIFEST_CLI_ENV_EXAMPLE_HEADER_SCAFFOLDED")"
    plan_names+=(".env.example")
    plan_states+=("$example_state")

    local emit_k8s=false
    local -a secret_drift_lines=()
    local kustomization_rendered="" kustomization_state="" configmap_state="" secret_state="" component_state=""
    if [[ -d "$project_root/k8s" ]]; then
        emit_k8s=true
        # The kustomization lists exactly what Manifest renders. A
        # hand-authored external-secret.yaml that Manifest renders no bridge
        # for (provider none, or no secrets declared) is NOT added to it: an
        # adopter in that state already references the file from their own
        # kustomization, and listing it here too fails their build with a
        # duplicate resource id.
        kustomization_rendered="$(_manifest_env_render_env_kustomization "$spec_file" "$emit_secret_bridge")"
        # Every k8s/env file is marker-guarded. The kustomization was first:
        # an adopter who consumed the bridges before that file existed had to
        # author one here themselves, often with more in it, and replacing it
        # would drop resources from their next build silently.
        kustomization_state="$(_manifest_env_guarded_state "$project_root/k8s/env/kustomization.yaml" "$kustomization_rendered" "$MANIFEST_CLI_ENV_K8S_HEADER")"
        plan_names+=("k8s/env/kustomization.yaml")
        plan_states+=("$kustomization_state")
        configmap_state="$(_manifest_env_guarded_state "$project_root/k8s/env/configmap.yaml" "$configmap_rendered" "$MANIFEST_CLI_ENV_K8S_HEADER")"
        plan_names+=("k8s/env/configmap.yaml")
        plan_states+=("$configmap_state")
        if [[ "$emit_secret_bridge" == "true" ]]; then
            secret_state="$(_manifest_env_guarded_state "$project_root/k8s/env/external-secret.yaml" "$external_rendered" "$MANIFEST_CLI_ENV_K8S_HEADER")"
            plan_names+=("k8s/env/external-secret.yaml")
            plan_states+=("$secret_state")
            if [[ "$secret_state" == "update" ]]; then
                local drift_line
                while IFS= read -r drift_line; do
                    [[ -n "$drift_line" ]] && secret_drift_lines+=("$drift_line")
                done < <(_manifest_env_secrets_drift_detail "$project_root/k8s/env/external-secret.yaml" "$external_rendered")
            fi
        fi
        if [[ "$emit_component" == "true" ]]; then
            component_state="$(_manifest_env_guarded_state "$project_root/k8s/env/component/kustomization.yaml" "$component_rendered" "$MANIFEST_CLI_ENV_K8S_HEADER")"
            plan_names+=("k8s/env/component/kustomization.yaml")
            plan_states+=("$component_state")
        fi
    fi

    local emit_bridge=false
    if [[ -n "$bridge_rendered" && -f "$project_root/Dockerfile" ]]; then
        emit_bridge=true
        plan_names+=("Dockerfile (bridge block)")
        if [[ "$(_manifest_env_dockerfile_bridge_current "$project_root/Dockerfile")" == "$bridge_rendered" ]]; then
            plan_states+=("current")
        elif grep -qF "$MANIFEST_CLI_ENV_BRIDGE_BEGIN" "$project_root/Dockerfile" 2>/dev/null; then
            plan_states+=("update")
        else
            plan_states+=("create")
        fi
    fi

    # ---- Report the plan -----------------------------------------------------
    echo ""
    if [[ "$check_only" == "true" ]]; then
        echo "Env drift check — $project_root"
    elif [[ "$apply" == "true" ]]; then
        echo "Generating env artifacts: $project_root"
    else
        echo "Dry run — manifest env generate: $project_root"
    fi
    echo ""

    local i drift=0 blocked=0
    for i in "${!plan_names[@]}"; do
        case "${plan_states[$i]}" in
            current) echo "  up-to-date:   ${plan_names[$i]}" ;;
            blocked)
                echo "  cannot read:  ${plan_names[$i]} (not a readable file; not compared, and -y will not write it)"
                blocked=$((blocked + 1))
                ;;
            foreign)
                if [[ "${plan_names[$i]}" == "k8s/env/kustomization.yaml" ]]; then
                    echo "  hand-authored, left untouched: ${plan_names[$i]} (list configmap.yaml$([[ "$emit_secret_bridge" == "true" ]] && printf ' and external-secret.yaml') in it yourself)"
                else
                    echo "  hand-authored, left untouched: ${plan_names[$i]} (its first line is not Manifest's header; delete the file to have it generated)"
                fi
                ;;
            create)  echo "  would create: ${plan_names[$i]}"; drift=$((drift + 1)) ;;
            update)
                echo "  would update: ${plan_names[$i]}"
                drift=$((drift + 1))
                if [[ "${plan_names[$i]}" == "k8s/env/external-secret.yaml" && ${#secret_drift_lines[@]} -gt 0 ]]; then
                    local d
                    for d in "${secret_drift_lines[@]}"; do
                        echo "                $d"
                    done
                fi
                ;;
        esac
    done
    echo ""

    if [[ "$check_only" == "true" ]]; then
        if [[ "$drift" -gt 0 ]]; then
            echo "env drift: $drift artifact(s) stale — run: manifest env generate -y"
        fi
        if [[ "$blocked" -gt 0 ]]; then
            echo "env drift: $blocked path(s) could not be read, so nothing is known about them"
        fi
        [[ "$drift" -eq 0 && "$blocked" -eq 0 ]] || return 1
        echo "env drift: clean"
        return 0
    fi

    if [[ "$apply" != "true" ]]; then
        manifest_execution_footer "manifest env generate -y"
        echo ""
        return 0
    fi

    # ---- Apply ---------------------------------------------------------------
    local failed=0
    _manifest_env_land "$project_root" ".env.example" "$example_state" "$example_rendered" || failed=$((failed + 1))
    if [[ "$emit_k8s" == "true" ]]; then
        _manifest_env_land "$project_root" "k8s/env/kustomization.yaml" "$kustomization_state" "$kustomization_rendered" || failed=$((failed + 1))
        _manifest_env_land "$project_root" "k8s/env/configmap.yaml" "$configmap_state" "$configmap_rendered" || failed=$((failed + 1))
        if [[ "$emit_secret_bridge" == "true" ]]; then
            _manifest_env_land "$project_root" "k8s/env/external-secret.yaml" "$secret_state" "$external_rendered" || failed=$((failed + 1))
        fi
        if [[ "$emit_component" == "true" ]]; then
            _manifest_env_land "$project_root" "k8s/env/component/kustomization.yaml" "$component_state" "$component_rendered" || failed=$((failed + 1))
        fi
    fi
    if [[ "$emit_bridge" == "true" ]]; then
        if _manifest_env_dockerfile_bridge_apply "$project_root/Dockerfile" "$bridge_rendered"; then
            echo "  wrote: Dockerfile bridge block"
        else
            echo "  FAILED: Dockerfile bridge block (not written)"
            failed=$((failed + 1))
        fi
    fi
    echo ""
    if [[ "$failed" -gt 0 ]]; then
        echo "Env artifacts NOT fully generated: $failed file(s) could not be written."
        return 1
    fi
    echo "Env artifacts generated."
    return 0
}

# manifest env validate — read-only: env prefix policy + drift + gitignore hygiene.
manifest_env_validate() {
    if [[ "${1:-}" == "--help" || "${1:-}" == "help" ]]; then
        _render_help \
            "manifest env validate" \
            "Validate env hygiene: prefix policy, generated-artifact drift, gitignore." \
            "Checks" "  prefix     stored names carry the repo prefix (derived unless env.prefix set; off to disable)
  drift      .env.example and k8s/env/* match the spec env: block and env.secrets
             (a store or path that differs from config is named; secrets declared
             with no env.secrets configured is reported as a configuration gap)
  gitignore  .env value files are ignored; only example/template tracked"
        return 0
    fi

    local project_root="${MANIFEST_CLI_PROJECT_ROOT:-$(pwd)}"
    local failures=0

    echo ""
    echo "Env validation — $project_root"
    echo ""

    local _policy_prefix
    _policy_prefix="$(_manifest_env_effective_prefix "$project_root")"
    if [[ -z "$_policy_prefix" ]]; then
        echo "  env prefix policy:"
        echo "      ℹ️  disabled (env.prefix: off) — no owned-var prefix is required"
    else
        echo "  env prefix policy (prefix: ${_policy_prefix}, enforcement: ${MANIFEST_CLI_ENV_NAMING_ENFORCEMENT:-strict}):"
        if check_env_naming "$project_root"; then
            echo "      ✅ stored names conform"
        else
            if [[ "${MANIFEST_CLI_ENV_NAMING_ENFORCEMENT:-strict}" == "strict" ]]; then
                failures=$((failures + 1))
                echo "      ❌ violations (strict)"
            else
                echo "      ⚠️  violations (warn)"
            fi
        fi
    fi

    echo "  generated-artifact drift:"
    if _manifest_env_spec_ready "$project_root"; then
        local check_out check_rc=0
        check_out="$(manifest_env_generate --check 2>&1)" || check_rc=$?
        if [[ "$check_rc" -eq 0 ]]; then
            echo "      ✅ artifacts match the spec env: block and env.secrets"
            # A hand-authored file is not compared, so say which ones were not.
            printf '%s\n' "$check_out" | sed -n 's/^  hand-authored, left untouched: \([^ ]*\).*/      ℹ️  not compared (hand-authored): \1/p'
        elif printf '%s\n' "$check_out" | grep -q '^env spec — cannot generate'; then
            # Refused before the store gate: a flag value the reader does not
            # guess. Nothing was compared.
            echo "      ❌ spec flags — a secret, required or public flag is neither true nor false:"
            printf '%s\n' "$check_out" | sed -n '/ — write true or false$/p' | sed 's/^ */          /'
            failures=$((failures + 1))
        elif printf '%s\n' "$check_out" | grep -q '^env.secrets — cannot generate'; then
            # The gate refused before rendering: this is a configuration gap,
            # not stale output, and the fix is different.
            echo "      ❌ secret store not configured — secrets are declared but env.secrets is unset or invalid:"
            printf '%s\n' "$check_out" | sed -n '/^  env.secrets/p' | sed 's/^/          /'
            failures=$((failures + 1))
        else
            if printf '%s\n' "$check_out" | grep -q '^env drift: .* stale'; then
                echo "      ❌ stale artifacts — run: manifest env generate -y"
            fi
            printf '%s\n' "$check_out" | sed -n 's/^  cannot read:  \([^ ]*\).*/      ❌ cannot read: \1 (not a readable file) — not compared/p'
            printf '%s\n' "$check_out" | grep -E '^ +(store|path) drift:' | sed 's/^ */          /'
            printf '%s\n' "$check_out" | sed -n 's/^  hand-authored, left untouched: \([^ ]*\).*/      ℹ️  not compared (hand-authored): \1/p'
            failures=$((failures + 1))
        fi
    else
        echo "      ℹ️  no spec env: block — nothing generated yet"
    fi

    echo "  gitignore hygiene:"
    if git -C "$project_root" rev-parse --git-dir >/dev/null 2>&1; then
        if check_environment_file_security "$project_root" >/dev/null; then
            echo "      ✅ env value files are git-ignored"
        else
            echo "      ❌ env value files exist that are NOT git-ignored"
            failures=$((failures + 1))
        fi
    else
        echo "      ℹ️  not a git repository — skipped"
    fi

    echo ""
    if [[ "$failures" -gt 0 ]]; then
        echo "env validate: FAIL ($failures check(s))"
        return 1
    fi
    echo "env validate: PASS"
    return 0
}

# Dispatch for `manifest env <generate|validate>`
manifest_env_dispatch() {
    case "${1:-}" in
        generate)
            shift || true
            manifest_env_generate "$@"
            ;;
        validate)
            shift || true
            manifest_env_validate "$@"
            ;;
        help|--help|"")
            _render_help \
                "manifest env <generate|validate>" \
                "Keep your environment-variable names in one place — the spec's env: block —
and generate the per-target files from it." \
                "Subcommands" "  generate   Write .env.example, plus Kubernetes and Dockerfile files, from
             the spec's env: block
  validate   Check variable-name prefixes, whether the generated files are
             out of date, and that real .env files are gitignored (read-only)"
            [[ -z "${1:-}" ]] && return 1
            return 0
            ;;
        *)
            _render_help_error "Unknown env subcommand: $1" "manifest env <generate|validate>"
            return 1
            ;;
    esac
}
